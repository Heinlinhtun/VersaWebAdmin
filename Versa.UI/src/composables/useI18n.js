const resolvePath = (obj, key) => {
  return key
    .split(".")
    .reduce((acc, part) => (acc && part in acc ? acc[part] : undefined), obj);
};

const interpolate = (text, params = {}) => {
  if (!params || typeof text !== "string") return text;
  return text.replace(/\{(\w+)\}/g, (_, token) =>
    String(params[token] ?? `{${token}}`),
  );
};

export function useI18n() {
  const setLocale = (nextLocale) => {
    if (!SUPPORTED_LOCALES.includes(nextLocale)) return;
    locale.value = nextLocale;
    localStorage.setItem(LOCALE_KEY, nextLocale);
    document.documentElement.lang = nextLocale === "mm" ? "my" : "en";
    document.documentElement.classList.toggle("lang-mm", nextLocale === "mm");
  };

  const t = (key, params) => {
    const current = resolvePath(messages[locale.value], key);
    if (current !== undefined) return interpolate(current, params);

    const fallback = resolvePath(messages.en, key);
    return fallback !== undefined ? interpolate(fallback, params) : key;
  };

  const isMM = computed(() => locale.value === "mm");

  return {
    locale,
    isMM,
    setLocale,
    t,
    supportedLocales: SUPPORTED_LOCALES,
  };
}
